package org.chromium.ax.android.mojom;

import org.chromium.mojo.bindings.DeserializationException;

public final class ActionStringArgumentType {
    public static final int HTML_ELEMENT_STRING = 0;
    public static final int SET_TEXT_CHARSEQUENCE = 1;

    private ActionStringArgumentType() {
    }

    public static boolean isKnownValue(int i) {
        return i == 0 || i == 1;
    }

    public static void validate(int i) {
        if (!isKnownValue(i)) {
            throw new DeserializationException("Invalid enum value.");
        }
    }
}
